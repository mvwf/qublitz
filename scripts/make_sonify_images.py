"""Write web/qublitz/sonify-images.js: the Sonify page's preloaded images as data URIs.

The page sonifies the grayscale pixels, so each image in sonify_images/ (listed in
sonify_images/image_helper.json) is stored as an 8-bit grayscale PNG, converted with the
same PIL .convert("L") the Streamlit page uses. Images wider than 16384 columns (the
84672-column Bloop clip) are block-averaged down to 16384, the cap the page already
applies when it converts a sound file, since browsers cannot hold wider canvases.
Photos also get a small color JPEG preview for the "original image" view.

Shipping them as a script (rather than separate files) lets scripts/build_standalone.py
inline them, so the downloadable single-file page has the gallery too.

Usage (from the repo root):
    python scripts/make_sonify_images.py
"""
import base64
import io
import json
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "sonify_images")
OUT = os.path.join(ROOT, "web", "qublitz", "sonify-images.js")
MAX_COLS = 16384
PREVIEW = 360        # longest side of the color preview, in px


def data_uri(img, fmt, **kw):
    buf = io.BytesIO()
    img.save(buf, fmt, **kw)
    mime = "image/png" if fmt == "PNG" else "image/jpeg"
    return f"data:{mime};base64," + base64.b64encode(buf.getvalue()).decode("ascii")


def main():
    with open(os.path.join(SRC, "image_helper.json"), encoding="utf-8") as f:
        entries = json.load(f)
    out = []
    for e in entries:
        img = Image.open(os.path.join(SRC, e["filename"]))
        gray = img.convert("L")
        if gray.width > MAX_COLS:
            gray = gray.resize((MAX_COLS, gray.height), Image.BOX)
        item = {"name": os.path.splitext(e["filename"])[0], "text": e.get("text", ""),
                "link": e.get("link", ""), "gray": data_uri(gray, "PNG", optimize=True)}
        # Waveform strips (64 rows) are their own preview; photos get a small color JPEG.
        if img.height > 64:
            rgba = img.convert("RGBA")
            flat = Image.new("RGB", rgba.size, "white")
            flat.paste(rgba, mask=rgba.split()[3])
            flat.thumbnail((PREVIEW, PREVIEW))
            item["preview"] = data_uri(flat, "JPEG", quality=82)
        out.append(item)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/make_sonify_images.py from sonify_images/. Do not edit. */\n")
        f.write("window.SONIFY_IMAGES = ")
        json.dump(out, f, separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")
    print(f"wrote {OUT} ({os.path.getsize(OUT) / 1e6:.1f} MB, {len(out)} images)")


if __name__ == "__main__":
    main()
